export function chooseAgents(userRequest, mode = "auto") {
  if (mode === "all") {
    return ["analyst", "tech", "marketer"];
  }

  const text = userRequest.toLowerCase();
  const selected = new Set(["analyst"]);

  const techWords = [
    "сайт",
    "бот",
    "прилож",
    "код",
    "api",
    "интеграц",
    "автоматизац",
    "telegram",
    "whatsapp",
    "crm",
    "supabase",
    "база",
    "сервер",
  ];

  const marketingWords = [
    "продаж",
    "монет",
    "клиент",
    "оффер",
    "лендинг",
    "реклам",
    "заявк",
    "услуг",
    "цена",
    "пакет",
  ];

  if (techWords.some((word) => text.includes(word))) {
    selected.add("tech");
  }

  if (marketingWords.some((word) => text.includes(word))) {
    selected.add("marketer");
  }

  return [...selected];
}

